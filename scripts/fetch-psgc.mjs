// One-off data script: builds data/locations/psgc-data.js from the Philippine Standard
// Geographic Code (PSGC) published by the Philippine Statistics Authority (PSA).
//
// psa.gov.ph blocks automated downloads, so this reads the PSGC API at psgc.gitlab.io,
// which republishes the PSA PSGC tables. The result is cross-checked against the list in
// SEO-EXPANSION-PROMPT.md (Part 5). Re-run after a new PSGC release:
//   node scripts/fetch-psgc.mjs
import { writeFileSync } from "node:fs";

const api = "https://psgc.gitlab.io/api";
const headers = { "User-Agent": "dmsa-site-build" };

// Provinces DMSA serves. NCR has no provinces, so it is read by region.
const sources = [
  { name: "Laguna", path: "/provinces/043400000" },
  { name: "Batangas", path: "/provinces/041000000" },
  { name: "Cavite", path: "/provinces/042100000" },
  { name: "Rizal", path: "/provinces/045800000" },
  { name: "Quezon", path: "/provinces/045600000" },
  { name: "Metro Manila", path: "/regions/130000000" },
  { name: "Albay", path: "/provinces/050500000" },
  { name: "Camarines Norte", path: "/provinces/051600000" },
  { name: "Camarines Sur", path: "/provinces/051700000" },
  { name: "Catanduanes", path: "/provinces/052000000" },
  { name: "Masbate", path: "/provinces/054100000" },
  { name: "Sorsogon", path: "/provinces/056200000" },
];

// Cities whose plain name would read like the province (or another place), so they keep "City".
const keepCity = new Set(["Batangas", "Cavite", "Masbate", "Sorsogon", "Quezon"]);

// The API lags behind these cityhood laws, so they are corrected here.
const becameCities = {
  Calaca: "RA 11787, ratified 2022",
  Carmona: "RA 11938, ratified 2023",
};

// Abbreviations and casing in the source, written out the way people search for them.
const spellingFixes = {
  "Sto. Tomas": "Santo Tomas",
  "Gen. Mariano Alvarez": "General Mariano Alvarez",
  "Pio v. Corpuz": "Pio V. Corpuz",
};

async function get(path) {
  const response = await fetch(`${api}${path}`, { headers });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.json();
}

/** "City of Biñan" → "Biñan", "Pasay City" → "Pasay", "City of Batangas" → "Batangas City". */
function displayName(raw, isCity, oldName) {
  const alias = /\(([^)]+)\)/.exec(raw)?.[1] || oldName?.trim() || undefined;
  let name = raw.replace(/\s*\([^)]*\)\s*/g, " ").trim();
  if (isCity) {
    name = name.replace(/^City of\s+/i, "").replace(/\s+City$/i, "").trim();
    if (keepCity.has(name)) name = `${name} City`;
  }
  return { name: spellingFixes[name] ?? name, alias };
}

const collator = new Intl.Collator("en", { sensitivity: "base", numeric: true });
const provinces = [];

for (const source of sources) {
  const [towns, barangays] = await Promise.all([
    get(`${source.path}/cities-municipalities/`),
    get(`${source.path}/barangays/`),
  ]);
  const byTown = new Map();
  for (const barangay of barangays) {
    const townCode = barangay.cityCode || barangay.municipalityCode;
    if (!byTown.has(townCode)) byTown.set(townCode, []);
    byTown.get(townCode).push(barangay.name.trim());
  }
  provinces.push({
    name: source.name,
    towns: towns
      .map((town) => {
        const isCity = town.isCity || Boolean(becameCities[town.name]);
        const { name, alias } = displayName(town.name, isCity, town.oldName);
        return {
          code: town.code,
          name,
          ...(alias ? { alias } : {}),
          officialName: becameCities[town.name] ? `City of ${town.name}` : town.name,
          type: isCity ? "city" : "municipality",
          barangays: (byTown.get(town.code) ?? []).sort(collator.compare),
        };
      })
      .sort((a, b) => collator.compare(a.name, b.name)),
  });
  console.log(`${source.name}: ${towns.length} cities/municipalities, ${barangays.length} barangays`);
}

const total = provinces.reduce((sum, province) => sum + province.towns.length, 0);
const missing = provinces.flatMap((p) => p.towns.filter((t) => t.barangays.length === 0).map((t) => `${t.name}, ${p.name}`));
if (missing.length) console.warn("No barangays found for:", missing.join("; "));
console.log(`Total: ${total} cities and municipalities`);

const banner = `// Generated by scripts/fetch-psgc.mjs from the PSA Philippine Standard Geographic Code
// (via the PSGC API at psgc.gitlab.io) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand:
// re-run the script instead. Owner-supplied local details go in town-notes.js.
`;
writeFileSync(
  new URL("../data/locations/psgc-data.js", import.meta.url),
  `${banner}\n/** @type {import("../../lib/content-types").PsgcProvince[]} */\nexport const psgcProvinces = ${JSON.stringify(provinces, null, 1)};\n`,
);
