// One-off data script: looks up the town-centre coordinates of every city and municipality
// in data/locations/psgc-data.js from OpenStreetMap (Nominatim) and writes
// data/locations/coordinates-data.js. Coordinates are only used to measure approximate
// straight-line distances and to sort nearby towns and jobs.
//
// Follows the Nominatim usage policy: one request per second, an application User-Agent,
// and results cached in the repo so the build never calls the service.
//   node scripts/fetch-coordinates.mjs            (only towns not yet cached)
//   node scripts/fetch-coordinates.mjs --refresh  (all towns)
import { existsSync, writeFileSync } from "node:fs";

import { psgcProvinces } from "../data/locations/psgc-data.js";

const output = new URL("../data/locations/coordinates-data.js", import.meta.url);
const refresh = process.argv.includes("--refresh");
const cached = !refresh && existsSync(output) ? (await import(output.href)).townCoordinates : {};
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const plain = (value = "") => value.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/\bcity\b|\bcity of\b/g, "").replace(/[^a-z]/g, "");

async function lookup(query, province, townName) {
  const url = new URL("https://nominatim.openstreetmap.org/search");
  url.search = new URLSearchParams({ q: query, format: "jsonv2", limit: "8", countrycodes: "ph", addressdetails: "1" }).toString();
  const response = await fetch(url, { headers: { "User-Agent": "dmsa-site-build" } });
  if (!response.ok) throw new Error(`HTTP ${response.status} for ${query}`);
  const results = await response.json();
  // City/municipality boundaries are admin level 6 (place rank 12-14) in the Philippines.
  const inProvince = (r) => province === "Metro Manila"
    ? r.address?.region === "Metro Manila" || r.address?.state === "Metro Manila"
    : r.address?.state === province || r.address?.province === province;
  const boundary = results.find((r) => r.category === "boundary" && r.type === "administrative" && r.place_rank >= 10 && r.place_rank <= 14 && inProvince(r));
  // Some towns are mapped only as a town-centre point. Accept it when the name matches.
  const point = results.find((r) => r.category === "place" && ["city", "town", "municipality", "village"].includes(r.type) && inProvince(r)
    && plain(r.address?.city ?? r.address?.town ?? r.address?.municipality ?? r.name) === plain(townName));
  const match = boundary ?? point;
  return match ? [Number(Number(match.lon).toFixed(4)), Number(Number(match.lat).toFixed(4))] : null;
}

// Towns the search above can't match, checked by hand on OpenStreetMap:
// Lucena and Naga are independent cities with no province in OSM, and OSM spells
// Pio V. Corpuz as "Pio V. Corpus".
const manual = {
  "045624000": [121.6135, 13.9269], // Lucena: downtown, Quezon Avenue (Lucena City station)
  "051724000": [123.185, 13.624], // Naga City boundary label point
  "054116000": [124.0489, 11.8837], // Pio V. Corpus town node
};

const coordinates = { ...manual, ...cached };
const failures = [];
for (const province of psgcProvinces) {
  for (const town of province.towns) {
    if (coordinates[town.code]) continue;
    const queries = [`${town.name}, ${province.name}, Philippines`, `${town.officialName}, ${province.name}, Philippines`];
    let found = null;
    for (const query of [...new Set(queries)]) {
      found = await lookup(query, province.name, town.name);
      await sleep(1100);
      if (found) break;
    }
    if (found) coordinates[town.code] = found;
    else failures.push(`${town.name}, ${province.name} (${town.code})`);
    console.log(`${found ? "✓" : "✗"} ${town.name}, ${province.name}`);
  }
}

// Flag points far from the rest of their province for manual review.
const distanceKm = ([lng1, lat1], [lng2, lat2]) => {
  const rad = Math.PI / 180;
  const a = Math.sin(((lat2 - lat1) * rad) / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(((lng2 - lng1) * rad) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(a));
};
const outliers = [];
for (const province of psgcProvinces) {
  const points = province.towns.map((town) => coordinates[town.code]).filter(Boolean);
  for (const town of province.towns) {
    const point = coordinates[town.code];
    if (!point) continue;
    const nearest = Math.min(...points.filter((other) => other !== point).map((other) => distanceKm(point, other)));
    if (nearest > 40) outliers.push(`${town.name}, ${province.name}: nearest other town ${Math.round(nearest)} km`);
  }
}

const sorted = Object.fromEntries(Object.entries(coordinates).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  output,
  `// Generated by scripts/fetch-coordinates.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL).
// Town-centre [longitude, latitude] by PSGC code. Used only for approximate distances.

/** @type {Record<string, [number, number]>} */
export const townCoordinates = ${JSON.stringify(sorted, null, 1).replace(/\[\n\s+([\d.]+),\n\s+([\d.]+)\n\s+\]/g, "[$1, $2]")};
`,
);
console.log(`\n${Object.keys(sorted).length} towns with coordinates.`);
if (failures.length) console.log("Not found (add by hand):\n  " + failures.join("\n  "));
if (outliers.length) console.log("Check these (more than 40 km from any other town in the province):\n  " + outliers.join("\n  "));
